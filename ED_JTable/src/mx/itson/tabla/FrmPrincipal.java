    private void pintarTabla(){
        //vaciar la tabla
        modelo.setRowCount(0);
        //pintar cada elemento
        for(Producto p : productos){
            Object[] fila = {p.getNombre(), p.getPiezas(), p.getPrecio()};
            modelo.addRow(fila);
        }
        //colocar de nuevo el modelo de la tabla 
        tblProductos.setModel(modelo);
    }
    
