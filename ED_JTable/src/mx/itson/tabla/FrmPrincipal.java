    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
                                         
        String nombre = tfNombreProducto.getText().trim();
        String cantidadTexto = tfCantidad.getText().trim();
        String precioTexto = tfPrecio.getText().trim();

        // Validar campos vacíos
        if (nombre.isEmpty() || cantidadTexto.isEmpty() || precioTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int piezas;
        double precio;

        //validar que piezas y precio sean números válidos
        try {
            piezas = Integer.parseInt(cantidadTexto);
            precio = Double.parseDouble(precioTexto);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La cantidad y el precio deben ser valores numericos", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }

        //validar que los valores sean mayores a cero
        if (piezas <= 0 || precio <= 0) {
            JOptionPane.showMessageDialog(this, "La cantidad y el precio deben ser mayores a 0", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }

        //crear un objeto producto y agregarlo a la lista
        Producto producto = new Producto(nombre, piezas, precio);
        productos.add(producto);

        //limpiar campos y actualizar tabla
        limpiarCampos();
        pintarTabla();

    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        //tomar el indice seleccionado en la tabla
        int filaseleccionada = tblProductos.getSelectedRow();
        if (filaseleccionada != -1){
            productos.remove(filaseleccionada);
        }else{
            JOptionPane.showMessageDialog(this,"No hay fila seleccionada", "ERROR" ,JOptionPane.ERROR_MESSAGE);
        } 
        //quitar el elementode la lista
        pintarTabla();
    }//GEN-LAST:event_btnEliminarActionPerformed

